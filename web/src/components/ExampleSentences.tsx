import { AnnotatedSentence } from '../lib/furigana';
import type { ExampleSentence } from '../types/curriculumRaw';
import { RelatedChips } from './RelatedChips';

type Props = {
  sentences: ExampleSentence[] | undefined;
  showReadings: boolean;
  generatorModel?: string;
};

export function ExampleSentences({ sentences, showReadings, generatorModel }: Props) {
  if (!sentences || sentences.length === 0) {
    return <p className="panel-muted">No example sentences.</p>;
  }

  const sorted = [...sentences].sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0));

  return (
    <>
      {generatorModel ? <p className="panel-muted example-list__model">Generated by: {generatorModel}</p> : null}
      <ul className="example-list">
        {sorted.map((sentence, i) => (
          <li key={i} className="example-item">
            <p className="example-japanese">
              <AnnotatedSentence
                text={sentence.japanese}
                furigana={sentence.furigana}
                wordSpans={sentence.word_spans}
                showReadings={showReadings}
              />
            </p>
            <p className="example-english">{sentence.english}</p>
            {sentence.vocabulary_slugs && sentence.vocabulary_slugs.length > 0 ? (
              <RelatedChips type="vocabulary" slugs={sentence.vocabulary_slugs} />
            ) : null}
          </li>
        ))}
      </ul>
    </>
  );
}
