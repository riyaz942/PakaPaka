def cmd_context(args):
    """Dry run: what one seed resolves to, without calling anything."""
    problems = reading_seeds.seed_errors(args.level)
    for problem in problems:
        print(f"SEED PROBLEM: {problem}")
    for slug in args.slugs:
        ctx = rc.seed_context(args.level, slug)
        lo, hi = ctx["target_words"]
        print(f"\n=== {slug} ===")
        print(f"position       {ctx['seed']['position']} of "
              f"{len(reading_seeds.seeds_for(args.level))}")
        print(f"tone           {ctx['tone']}")
        print(f"target words   {lo}–{hi}")
        print(f"questions      {ctx['question_count']}")
        print(f"allowed vocab  {len(ctx['allowed'])} words "
              f"(first: {ctx['allowed'][0]['primary_form']}, "
              f"last: {ctx['allowed'][-1]['primary_form']})")
        print(f"allowed grammar {len(ctx['allowed_grammar'])} points "
              f"(last: {ctx['allowed_grammar'][-1]['primary_form']})")
        print(f"required grammar {ctx['required_grammar_slugs'] or '(none assigned)'}")
        print(f"span forms     {len(ctx['span_forms'])} markable dictionary forms")
        print(f"extra allowed  {sorted(ctx['extra_allowed']) or '(none)'}")
        prompt = build_user_prompt(ctx)
        print(f"prompt         {len(prompt)} chars")
        if args.show_prompt:
            print("-" * 60)
            print(prompt)


def cmd_requests(args):
    contexts = {slug: rc.seed_context(args.level, slug) for slug in args.slugs}
    requests = [build_request(args.level, slug, 1, contexts[slug]) for slug in args.slugs]
    out = os.path.join(DRAFTS_DIR, args.level, "requests-preview.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(requests, f, ensure_ascii=False, indent=2)
    total_chars = sum(len(r["params"]["messages"][0]["content"]) for r in requests)
    print(f"wrote {len(requests)} request payloads to {out} (~{total_chars} prompt chars)")


def cmd_run(args):
    import anthropic

    problems = reading_seeds.seed_errors(args.level)
    if problems:
        raise SystemExit("fix the seed list first:\n  " + "\n  ".join(problems))

    client = anthropic.Anthropic()
    contexts = {slug: rc.seed_context(args.level, slug) for slug in args.slugs}
    records = {slug: _load_draft(args.level, slug) for slug in args.slugs}

    # Resumable: re-validate stored output against the *current* gate first.
    pending = {}
    for slug in args.slugs:
        record = records[slug]
        if record["tool_input"] is not None:
            errors = validate_draft(args.level, slug, record["tool_input"], contexts[slug])
            if not errors:
                if record["status"] != "draft":
                    record["status"] = "draft"
                    _save_draft(record)
                print(f"{slug}: stored draft passes the current gate — skipping generation")
                continue
            pending[slug] = errors
        else:
            pending[slug] = None

    for attempt in range(1, MAX_ATTEMPTS + 1):
        if not pending:
            break
        requests = [
            build_request(args.level, slug, attempt, contexts[slug], errors)
            for slug, errors in pending.items()
        ]
        outcomes = _submit_and_collect(client, requests)
        pending = _process_outcomes(args.level, contexts, records, outcomes)

    for slug in pending:
        records[slug]["status"] = "flagged_for_rewrite"
        _save_draft(records[slug])
        print(f"{slug}: still failing after {MAX_ATTEMPTS} attempts — flagged_for_rewrite")

    write_dataset(args.level)


def cmd_collect(args):
    import anthropic

    if not args.batch_id:
        raise SystemExit("collect requires --batch-id msgbatch_...")
    client = anthropic.Anthropic()
    batch = client.messages.batches.retrieve(args.batch_id)
    if batch.processing_status != "ended":
        counts = batch.request_counts
        raise SystemExit(
            f"batch {args.batch_id} is still {batch.processing_status} "
            f"(processing={counts.processing}); try again later"
        )
    pending = _process_outcomes(args.level, {}, {}, _batch_outcomes(client, args.batch_id))
    write_dataset(args.level)
    if pending:
        print("still failing the gate — rerun `run` to requeue with feedback: "
              + ", ".join(sorted(pending)))


def cmd_assemble(args):
    write_dataset(args.level)


# --- assembly into the _build dataset --------------------------------------

def dataset_path(level):
    return os.path.join(PASSAGES_DIR, f"{level}.json")


def write_dataset(level):
    """Rebuild the level's passage dataset from every gate-passing draft.

    A **build artifact**, not a shippable readings file: each entry pairs the
    seed's plan (tone, position) with a schema-shaped passage carrying the
    derived enrichment. Idempotent — re-running reconstructs it from the drafts.
    """
    entries = []
    level_dir = os.path.join(DRAFTS_DIR, level)
    if os.path.isdir(level_dir):
        for slug in reading_seeds.all_slugs(level):
            path = os.path.join(level_dir, f"{slug}.json")
            if not os.path.exists(path):
                continue
            with open(path, encoding="utf-8") as f:
                record = json.load(f)
            if record.get("status") != "draft" or not record.get("tool_input"):
                continue
            ctx = rc.seed_context(level, slug)
            passage = enrich(record["tool_input"], ctx)
            passage["slug"] = slug
            passage["_meta"] = {
                "generator_model": record.get("generator_model", MODEL),
                # sidecarMeta.prompt_version is a string in the schema.
                "prompt_version": str(record.get("prompt_version", PROMPT_VERSION)),
                "review_status": "draft",
            }
            entries.append({
                "seed": slug,
                "position": ctx["seed"]["position"],
                "tone": ctx["tone"],
                "passage": passage,
            })

    dataset = {"jlpt_level": level.upper(), "passages": entries}
    path = dataset_path(level)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)
        f.write("\n")

    humorous = sum(1 for e in entries if e["tone"] == "humorous")
    print(f"wrote {len(entries)} passage(s) to {path} ({humorous} humorous)")
    print("this file does NOT ship — wiring it into curriculum/readings/"
          f"{level}.json retires the hand-authored passages and happens only "
          "after a human reads the whole level "
          "(docs/content/phase-4-reading-passage-tooling.md).")
    return path


# --- web-chat (no-API) lane, mirroring 2a/2b/2c -----------------------------

API_TOOL_LINE = "Call the `submit_reading_passage` tool exactly once with"
WEB_TOOL_LINE = (
    "Reply with **exactly one** fenced ```json code block and nothing after it. "
    "Do not call any tools, and do not add any commentary outside the block. "
    "The JSON object must use these exact key names, with"
)
WEB_SKELETON = (
    '```json\n{\n  "title": "...",\n  "body": "...",\n'
    '  "english_translation": "...",\n  "summary_ja": "...",\n'
    '  "summary_en": "...",\n  "questions": [\n    {\n      "prompt": "...",\n'
    '      "accepted_answers": ["...", "..."]\n    }\n  ]\n}\n```'
)


def _first_json_object(text):
    start = text.find("{")
    while start != -1:
        depth, in_str, esc = 0, False, False
        for i in range(start, len(text)):
            c = text[i]
            if in_str:
                if esc:
                    esc = False
                elif c == "\\":
                    esc = True
                elif c == '"':
                    in_str = False
            elif c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    try:
                        return json.loads(text[start:i + 1])
                    except json.JSONDecodeError:
                        break
        start = text.find("{", start + 1)
    raise SystemExit("no parseable JSON object found in the reply")


def _web_prompt_text(level, ctx, validator_errors=None):
    persona = _read_prompt("persona.md")
    body = build_user_prompt(ctx, validator_errors, tool_line=WEB_TOOL_LINE)
    header = (
        f"<!-- Paste EVERYTHING below this line into a fresh Claude or Gemini chat.\n"
        f"     Save the reply to web/readings/{level}/{ctx['slug']}.reply.md, then run:\n"
        f"       .venv/bin/python -m generate_content.generate_readings ingest \\\n"
        f"         --level {level} --slug {ctx['slug']} --model <claude-web|gemini-web>\n"
        f"-->\n\n"
    )
    return (
        header
        + "# Teaching voice — follow this in everything you write below\n\n"
        + persona.strip() + "\n\n---\n\n" + body.strip() + "\n\n"
        + "For reference the JSON has this shape (keep the key names exactly):\n\n"
        + WEB_SKELETON
        + "\n\nWrite all Japanese plain. Output only the single JSON block.\n"
    )


def _remove_staging_files(*paths):
    """Delete the paste-ready prompt/reply files once a slug has been ingested
    successfully — their content now lives in the draft + dataset, so leaving
    them behind just litters web/readings/<level>/."""
    for path in paths:
        if path and os.path.exists(path):
            os.remove(path)


def cmd_webprompts(args):
    out_dir = os.path.join(WEB_DIR, args.level)
    os.makedirs(out_dir, exist_ok=True)
    for slug in args.slugs:
        ctx = rc.seed_context(args.level, slug)
        path = os.path.join(out_dir, f"{slug}.prompt.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(_web_prompt_text(args.level, ctx))
        print(f"wrote {path}")


def cmd_ingest(args):
    if not args.slug:
        raise SystemExit("ingest requires --slug")
    reply_path = args.from_path or os.path.join(
        WEB_DIR, args.level, f"{args.slug}.reply.md")
    if not os.path.exists(reply_path):
        raise SystemExit(f"no reply at {reply_path} — paste the model's answer there first")
    with open(reply_path, encoding="utf-8") as f:
        tool_input = _first_json_object(f.read())

    ctx = rc.seed_context(args.level, args.slug)
    errors = validate_draft(args.level, args.slug, tool_input, ctx)
    record = _load_draft(args.level, args.slug)
    record["tool_input"] = tool_input
    record["generator_model"] = args.model
    record["prompt_version"] = PROMPT_VERSION
    record["attempts"].append({"attempt": len(record["attempts"]) + 1, "errors": errors})
    record["status"] = "draft" if not errors else "failed_validation"
    _save_draft(record)

    if errors:
        prompt_path = os.path.join(WEB_DIR, args.level, f"{args.slug}.prompt.md")
        os.makedirs(os.path.dirname(prompt_path), exist_ok=True)
        with open(prompt_path, "w", encoding="utf-8") as f:
            f.write(_web_prompt_text(args.level, ctx, errors))
        print(f"{args.slug}: {len(errors)} gate failure(s) — NOT assembled:")
        for e in errors:
            print(f"  - {e}")
        raise SystemExit(1)

    write_dataset(args.level)
    prompt_path = os.path.join(WEB_DIR, args.level, f"{args.slug}.prompt.md")
    _remove_staging_files(reply_path, prompt_path)
    print(f"{args.slug}: PASS — merged into the {args.level} passage dataset")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command",
                        choices=["context", "requests", "run", "assemble", "collect",
                                 "webprompts", "ingest"])
    parser.add_argument("--level", default="n5")
    parser.add_argument("--slugs", default=None,
                        help="comma-separated seed slugs (default: every seed of the level)")
    parser.add_argument("--slug", default=None, help="ingest only: single seed slug")
    parser.add_argument("--show-prompt", action="store_true",
                        help="context only: print the full rendered prompt")
    parser.add_argument("--from", dest="from_path", default=None,
                        help="ingest only: path to the pasted reply")
    parser.add_argument("--model", default="web-chat",
                        help="ingest only: provenance recorded in the dataset _meta")
    parser.add_argument("--batch-id", default=None,
                        help="collect only: the msgbatch_... id to fetch results from")
    args = parser.parse_args()
    if args.slugs:
        args.slugs = [s for s in args.slugs.split(",") if s]
    elif args.slug:
        args.slugs = [args.slug]
    else:
        args.slugs = reading_seeds.all_slugs(args.level)

    {"context": cmd_context, "requests": cmd_requests, "run": cmd_run,
     "assemble": cmd_assemble, "collect": cmd_collect,
     "webprompts": cmd_webprompts, "ingest": cmd_ingest}[args.command](args)


if __name__ == "__main__":
    main()
