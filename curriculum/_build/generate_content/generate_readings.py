# -*- coding: utf-8 -*-
"""Phase 4 reading-passage generator
(docs/content/content-pipeline-plan.md Phase 4, Rev 1 step R1.6).

Build-time generation on the maintainer machine, mirroring the 2b/2c pipelines:
one Message Batches request per **seed** (`reading_seeds.py`), structured output
via a single forced tool call, drafts under `generate_content/drafts/readings/`,
and — only after passing the closed-loop gate (`validate_readings.py`) —
assembled into a `_build` dataset.

## The closed loop

Phase 4 step 3: tokenize the output, reject anything outside the level, and
regenerate with the specific violations listed, capped at MAX_ATTEMPTS, then
`flagged_for_rewrite` (a model can get genuinely stuck needing an out-of-level
word; move on rather than loop). Failure feedback is appended to the prompt on
the next attempt, exactly as in 2c.

## Where the output lands, and where it does NOT

`assemble` writes `_build/generate_content/passages/<level>.json` — a **build
artifact**, not a shippable readings file. Nothing here writes
`curriculum/readings/<level>.json`: that file is generated by `generate.py`
from the `_build` datasets. The generated set retires all 10 committed N5
passages — that content decision is settled — but the swap waits on the Phase 5
human read of the whole level, which no script can stand in for. See
docs/content/phase-4-reading-passage-tooling.md for the wire-in procedure.

Enrichment (`grammar_slugs`, `word_spans`, `vocabulary_slugs`, `word_count`,
`body_furigana`, `prompt_furigana`) is computed in `_build` and stored in that
artifact, which is
the shape Rev 1's generator-drift fix requires: enrichment that lives only in
the shipped JSON gets silently wiped by the next regeneration while
`validate-schema` stays green.

Usage (from curriculum/_build, venv per requirements.txt):
    .venv/bin/python -m generate_content.generate_readings context --slug neko-to-shukudai
    .venv/bin/python -m generate_content.generate_readings requests
    .venv/bin/python -m generate_content.generate_readings run          # needs API credentials
    .venv/bin/python -m generate_content.generate_readings collect --batch-id msgbatch_...
    .venv/bin/python -m generate_content.generate_readings assemble
    .venv/bin/python -m generate_content.generate_readings webprompts   # no-API lane
    .venv/bin/python -m generate_content.generate_readings ingest --slug neko-to-shukudai
"""

