import json
import os
import sys
import time

BUILD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BUILD_DIR)

from generate_content import context as grammar_context  # noqa: E402
from generate_content import reading_context as rc  # noqa: E402
from generate_content import reading_seeds  # noqa: E402
from generate_content.validate_readings import enrich, validate_draft  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROMPTS_DIR = os.path.join(HERE, "prompts")
DRAFTS_DIR = os.path.join(HERE, "drafts", "readings")
WEB_DIR = os.path.join(HERE, "web", "readings")
PASSAGES_DIR = os.path.join(HERE, "passages")

MODEL = "claude-opus-5"
#: Bump together with prompts/reading-passage.md, persona.md, or the seed contract.
#: 2 — `grammar_slugs` left the submission (derived by `grammar_detect` now) and
#: the seed's `required_grammar` came in as a brief.
#: 3 — the sentence-craft block: subject dropping, lexical chaining, clause
#: joining where the window allows it (docs/content/
#: reading-passage-minna-no-nihongo-alignment.md, § 1).
PROMPT_VERSION = 3
MAX_ATTEMPTS = 3
#: Covers thinking *and* the submitted tool call. Opus 5 runs adaptive thinking
#: when `thinking` is omitted — Opus 4.8 did not — so the 3000 that sufficed
#: there truncates a passage here. A submission is ~1.5k tokens; the rest is
#: headroom for reasoning about the allowed-vocabulary constraint.
MAX_TOKENS = 8000
POLL_SECONDS = 30
POLL_TIMEOUT_SECONDS = 90 * 60

SUBMIT_TOOL = {
    "name": "submit_reading_passage",
    "description": (
        "Submit the completed reading passage for one seed. Call exactly once."
    ),
    "strict": True,
    "input_schema": {
        "type": "object",
        "additionalProperties": False,
        "required": [
            "title", "body", "english_translation", "summary_ja", "summary_en",
            "questions",
        ],
        "properties": {
            "title": {"type": "string"},
            "body": {"type": "string"},
            "english_translation": {"type": "string"},
            "summary_ja": {"type": "string"},
            "summary_en": {"type": "string"},
            "questions": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["prompt", "accepted_answers"],
                    "properties": {
                        "prompt": {"type": "string"},
                        "accepted_answers": {
                            "type": "array",
                            "items": {"type": "string"},
                        },
                    },
                },
            },
        },
    },
}

#: The tone tag from the seed, turned into prompt text. `humorous` points at the
#: comedy register in persona.md (which is in the system prompt); `neutral` says
#: plainly that this one is not a joke, so the register does not leak into the
#: whole level.
TONE_DIRECTIONS = {
    "humorous": (
        "**Tone: humorous.** Write this one funny, in the comedy register from "
        "the voice sheet above — an absurd situation reported deadpan, physical "
        "and specific, no wordplay that needs a word the learner does not have, "
        "and never a nudge at the reader. The passage still has to make plain "
        "sense as a reading: if the joke and the comprehension pull apart, the "
        "comprehension wins."
    ),
    "neutral": (
        "**Tone: neutral.** This one is not a joke. Write it warm and plain — a "
        "small true-feeling slice of a day, told straight. No punchline, no "
        "comic escalation."
    ),
}


def _read_prompt(name):
    with open(os.path.join(PROMPTS_DIR, name), encoding="utf-8") as f:
        return f.read()


def _feedback_block(validator_errors):
    if not validator_errors:
        return ""
    return (
        "\n## An earlier draft failed mechanical validation\n\n"
        "An earlier draft was rejected by the automated gate for the failures "
        "below. Write the passage so none of them recur:\n"
        + "\n".join(f"- {e}" for e in validator_errors)
    )


def _extra_allowed_block(ctx):
    names = sorted(ctx["extra_allowed"])
    if not names:
        return (
            "This passage has no named characters. If you need to refer to "
            "people, use words from the list above (友達, 先生, 母) rather than "
            "inventing a name."
        )
    return (
        "### Names you may use\n\n"
        "These names exist for this passage and nothing else does — do not "
        "invent others:\n\n"
        + "\n".join(f"- {name}" for name in names)
    )


def _required_grammar_block(ctx):
    """The seed's assigned grammar, briefed. Omitted when the seed has no
    assignment — which the level-wide coverage check
    (`reading_seeds.grammar_coverage_errors`) reports as a hole in its own
    right, so there is nothing to say about it here."""
    if not ctx["required_grammar"]:
        return ""
    return (
        "## Grammar this passage must use\n\n"
        "These points are assigned to this passage and to no other in the "
        "level, so each one has to appear in the body at least once:\n\n"
        + rc.format_grammar_list(ctx["required_grammar"])
        + "\n\nThe build finds them in your text with a tokenizer. You do not "
        "declare what you used; a point that is not really there fails the gate."
    )


def build_user_prompt(ctx, validator_errors=None, tool_line=None):
    template = _read_prompt("reading-passage.md")
    lo, hi = ctx["target_words"]
    subs = {
        "{{LEVEL}}": ctx["level"].upper(),
        "{{POSITION}}": str(ctx["seed"]["position"]),
        "{{SEED_COUNT}}": str(len(reading_seeds.seeds_for(ctx["level"]))),
        "{{TOPIC}}": ctx["topic"],
        "{{TONE_DIRECTION}}": TONE_DIRECTIONS[ctx["tone"]],
        "{{ALLOWED_VOCAB}}": grammar_context.format_vocab_list(ctx["allowed"]),
        "{{EXTRA_ALLOWED_BLOCK}}": _extra_allowed_block(ctx),
        "{{ALLOWED_GRAMMAR}}": rc.format_grammar_list(ctx["allowed_grammar"]),
        "{{REQUIRED_GRAMMAR_BLOCK}}": _required_grammar_block(ctx),
        "{{WORD_LO}}": str(lo),
        "{{WORD_HI}}": str(hi),
        "{{QUESTION_COUNT}}": str(ctx["question_count"]),
        "{{TOOL_LINE}}": tool_line or API_TOOL_LINE,
        "{{VALIDATOR_FEEDBACK}}": _feedback_block(validator_errors),
    }
    for token, value in subs.items():
        template = template.replace(token, value)
    return template


def build_request(level, slug, attempt, ctx, validator_errors=None):
    return {
        "custom_id": f"{level}--reading--{slug}--attempt{attempt}",
        "params": {
            "model": MODEL,
            "max_tokens": MAX_TOKENS,
            "system": _read_prompt("persona.md"),
            "tools": [SUBMIT_TOOL],
            "tool_choice": {"type": "tool", "name": SUBMIT_TOOL["name"]},
            "messages": [
                {"role": "user", "content": build_user_prompt(ctx, validator_errors)},
            ],
        },
    }


# --- draft persistence -----------------------------------------------------

def _draft_path(level, slug):
    return os.path.join(DRAFTS_DIR, level, f"{slug}.json")


def _load_draft(level, slug):
    path = _draft_path(level, slug)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return {"slug": slug, "level": level, "attempts": [], "status": "pending",
            "tool_input": None}


def _save_draft(record):
    path = _draft_path(record["level"], record["slug"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(record, f, ensure_ascii=False, indent=2)
        f.write("\n")


# --- batch plumbing --------------------------------------------------------

def _extract_tool_input(message):
    for block in message.content:
        if block.type == "tool_use" and block.name == SUBMIT_TOOL["name"]:
            return block.input
    return None


def _batch_outcomes(client, batch_id):
    outcomes = {}
    for result in client.messages.batches.results(batch_id):
        entry = result.result
        if entry.type == "succeeded":
            message = entry.message
            if message.stop_reason == "refusal":
                outcomes[result.custom_id] = {"error": "model refusal"}
                continue
            tool_input = _extract_tool_input(message)
            if tool_input is None:
                outcomes[result.custom_id] = {
                    "error": f"no tool call in response (stop_reason={message.stop_reason})"
                }
            else:
                outcomes[result.custom_id] = {"tool_input": tool_input}
        else:
            outcomes[result.custom_id] = {"error": f"batch result type {entry.type}"}
    return outcomes


def _submit_and_collect(client, requests):
    batch = client.messages.batches.create(requests=requests)
    print(f"submitted batch {batch.id} ({len(requests)} requests)")
    deadline = time.time() + POLL_TIMEOUT_SECONDS
    while True:
        batch = client.messages.batches.retrieve(batch.id)
        if batch.processing_status == "ended":
            break
        if time.time() > deadline:
            raise SystemExit(
                f"batch {batch.id} did not finish within the poll timeout; collect "
                f"it later with: generate_readings collect --batch-id {batch.id}"
            )
        counts = batch.request_counts
        print(f"  …{batch.processing_status} (processing={counts.processing} "
              f"succeeded={counts.succeeded} errored={counts.errored})")
        time.sleep(POLL_SECONDS)
    return _batch_outcomes(client, batch.id)


def _split_custom_id(custom_id):
    level, _kind, slug, attempt_part = custom_id.split("--")
    return level, slug, int(attempt_part.removeprefix("attempt"))


def _process_outcomes(level, contexts, records, outcomes):
    """Validate + persist batch outcomes; returns {slug: errors} still failing."""
    next_pending = {}
    for custom_id, outcome in outcomes.items():
        _, slug, attempt = _split_custom_id(custom_id)
        record = records.setdefault(slug, _load_draft(level, slug))
        ctx = contexts.setdefault(slug, rc.seed_context(level, slug))
        if "error" in outcome:
            record["attempts"].append({"attempt": attempt, "errors": [outcome["error"]]})
            next_pending[slug] = [outcome["error"]]
            print(f"[attempt {attempt}] {slug}: API-level failure: {outcome['error']}")
            _save_draft(record)
            continue
        tool_input = outcome["tool_input"]
        errors = validate_draft(level, slug, tool_input, ctx)
        record["attempts"].append({"attempt": attempt, "errors": errors})
        record["tool_input"] = tool_input
        record["generator_model"] = MODEL
        record["prompt_version"] = PROMPT_VERSION
        if errors:
            next_pending[slug] = errors
            record["status"] = "failed_validation"
            print(f"[attempt {attempt}] {slug}: {len(errors)} gate failure(s)")
            for e in errors:
                print(f"    - {e}")
        else:
            record["status"] = "draft"
            print(f"[attempt {attempt}] {slug}: PASS")
        _save_draft(record)
    return next_pending


